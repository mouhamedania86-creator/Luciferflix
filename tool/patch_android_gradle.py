#!/usr/bin/env python3
"""Patch the CI-generated Flutter Android project so the release build works.

Why this exists
---------------
`flutter_local_notifications` (>= 10) ships AAR metadata that declares
"core library desugaring required". The app module therefore has to enable
desugaring, otherwise the build dies with:

    Execution failed for task ':app:checkReleaseAarMetadata'.
    > Dependency ':flutter_local_notifications' requires core library
      desugaring to be enabled for :app.

The `android/` folder is regenerated by `flutter create` on every CI run
(see .github/workflows/build.yml), so the fix cannot live in a committed
Gradle file - it has to be applied to the generated project. That is what
this script does.

It also pins the SDK/NDK versions to concrete numbers instead of the
`flutter.*` placeholders, so a future `flutter create` template bump cannot
silently change the build (this repo rebuilds the Android project from
scratch on every single run).

The script is idempotent: running it twice produces the same file.
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

# --- what we pin the generated project to -----------------------------------
# These match the values current Flutter stable ships with
# (compileSdk 36 / minSdk 24 / targetSdk 36 / NDK 28.2.13676358).
COMPILE_SDK = "36"
MIN_SDK = "24"
TARGET_SDK = "36"
NDK_VERSION = "28.2.13676358"

# 2.1.5 is the current desugar_jdk_libs release (JDK11 based) and is the
# version recommended for AGP 9.x. The plugin's own docs still say 2.1.4,
# which also works - bump this if you ever need to.
DESUGAR_LIB = "com.android.tools:desugar_jdk_libs:2.1.5"

APP_DIR = Path("android/app")


def find_app_build_file() -> Path | None:
    for name in ("build.gradle.kts", "build.gradle"):
        candidate = APP_DIR / name
        if candidate.exists():
            return candidate
    return None


def pin_versions(src: str, kts: bool) -> str:
    """Replace `flutter.*` SDK placeholders with concrete values.

    Handles every shape the Flutter templates have used over time:
        compileSdk = flutter.compileSdkVersion      (Kotlin DSL / new Groovy)
        compileSdkVersion flutter.compileSdkVersion  (old Groovy DSL)
    """
    pins = [
        (r"\b(compileSdk(?:Version)?)\b\s*(=\s*)?flutter\.compileSdkVersion\b", COMPILE_SDK),
        (r"\b(targetSdk(?:Version)?)\b\s*(=\s*)?flutter\.targetSdkVersion\b", TARGET_SDK),
        (r"\b(minSdk(?:Version)?)\b\s*(=\s*)?flutter\.minSdkVersion\b", MIN_SDK),
        (r"\b(ndkVersion)\b\s*(=\s*)?flutter\.ndkVersion\b", f'"{NDK_VERSION}"'),
    ]

    for pattern, value in pins:
        def replace(match: re.Match) -> str:
            lhs, equals = match.group(1), match.group(2)
            if kts:
                return f"{lhs} = {value}"
            if equals:
                return f"{lhs} = {value}"
            return f"{lhs} {value}"

        src = re.sub(pattern, replace, src)
    return src


def ensure_desugaring_flag(src: str, kts: bool) -> str:
    """Turn on core library desugaring inside the `compileOptions` block."""
    flag = "isCoreLibraryDesugaringEnabled = true" if kts else "coreLibraryDesugaringEnabled true"

    # Already enabled? -> nothing to do.
    if re.search(r"(?m)^\s*isCoreLibraryDesugaringEnabled\s*=\s*true\b", src) or re.search(
        r"(?m)^\s*coreLibraryDesugaringEnabled\s+true\b", src
    ):
        return src

    # Explicitly turned off? -> flip it back on.
    if re.search(r"(?m)^\s*isCoreLibraryDesugaringEnabled\s*=\s*false\b", src):
        return re.sub(
            r"(?m)^(\s*isCoreLibraryDesugaringEnabled\s*=\s*)false\b", r"\1true", src
        )
    if re.search(r"(?m)^\s*coreLibraryDesugaringEnabled\s+false\b", src):
        return re.sub(
            r"(?m)^(\s*coreLibraryDesugaringEnabled\s+)false\b", r"\1true", src
        )

    match = re.search(r"(?m)^([ \t]*)compileOptions\s*\{", src)
    if match:
        indent = match.group(1) + "    "
        return src[: match.end()] + f"\n{indent}{flag}" + src[match.end() :]

    # No compileOptions block at all -> create one at the top of `android {`.
    flag_block = (
        f"\n    compileOptions {{\n"
        f"        {flag}\n"
        f"        sourceCompatibility = JavaVersion.VERSION_17\n"
        f"        targetCompatibility = JavaVersion.VERSION_17\n"
        f"    }}"
        if kts
        else f"\n    compileOptions {{\n"
        f"        {flag}\n"
        f"        sourceCompatibility JavaVersion.VERSION_17\n"
        f"        targetCompatibility JavaVersion.VERSION_17\n"
        f"    }}"
    )
    android_block = re.search(r"(?m)^android\s*\{", src)
    if not android_block:
        raise SystemExit("ERROR: could not find an `android {` block in the app build file.")
    return src[: android_block.end()] + flag_block + src[android_block.end() :]


def ensure_desugaring_dependency(src: str, kts: bool) -> str:
    """Add the coreLibraryDesugaring dependency to the app module."""
    # Only skip if a real declaration exists (not a stray mention in a comment).
    if re.search(r"coreLibraryDesugaring\s*[('\"(]", src):
        return src

    declaration = (
        f'coreLibraryDesugaring("{DESUGAR_LIB}")' if kts else f"coreLibraryDesugaring '{DESUGAR_LIB}'"
    )

    # Prefer the least indented `dependencies {` block (= the app module one).
    matches = list(re.finditer(r"(?m)^([ \t]*)dependencies\s*\{", src))
    if matches:
        best = min(matches, key=lambda m: len(m.group(1)))
        indent = best.group(1) + "    "
        return src[: best.end()] + f"\n{indent}{declaration}" + src[best.end() :]

    # The Flutter template has no top-level dependencies block -> create one.
    return (
        src.rstrip()
        + "\n\ndependencies {\n"
        + f"    {declaration}\n"
        + "}\n"
    )


def main() -> int:
    app_file = find_app_build_file()
    if app_file is None:
        raise SystemExit(
            "ERROR: android/app/build.gradle.kts (or .gradle) not found. "
            "Did the `flutter create` step run?"
        )

    kts = app_file.name.endswith(".kts")
    original = app_file.read_text(encoding="utf-8")

    patched = original
    patched = pin_versions(patched, kts)
    patched = ensure_desugaring_flag(patched, kts)
    patched = ensure_desugaring_dependency(patched, kts)

    if patched == original:
        print(f"Nothing to patch in {app_file} (already up to date).")
        return 0

    app_file.write_text(patched, encoding="utf-8")
    print(f"Patched {app_file} (Kotlin DSL: {kts})")
    print(f"  - core library desugaring enabled ({DESUGAR_LIB})")
    print(f"  - compileSdk={COMPILE_SDK} minSdk={MIN_SDK} targetSdk={TARGET_SDK} ndk={NDK_VERSION}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
